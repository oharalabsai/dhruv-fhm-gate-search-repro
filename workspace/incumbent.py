def hop_qubits(b):
    i, j = b, b + 1
    return ([tau(b), m_up(i), m_up(j)], [tau(b), m_dn(i), m_dn(j)])


def int_qubits(i):
    return [tau(i - 1), tau(i)]


def remap(gates, gmap):
    """Map a local native gate sequence onto global qubit indices."""
    mapped = []
    for gate in gates:
        if gate[0] in ("GPi", "GPi2", "RZ"):
            mapped.append((gate[0], gmap[gate[1]], gate[2]))
        elif gate[0] == "MS":
            mapped.append((gate[0], gmap[gate[1]], gmap[gate[2]], gate[3], gate[4], gate[5]))
        else:
            raise ValueError(f"unsupported gate: {gate[0]!r}")
    return mapped


def build_circuit():
    circ = []
    for b in range(N):
        qa, qb = hop_qubits(b)
        circ.extend(remap(HOP_GATES, {0: qa[0], 1: qa[1], 2: qa[2]}))
        circ.extend(remap(HOP_GATES, {0: qb[0], 1: qb[1], 2: qb[2]}))
    for i in range(N):
        q0, q1 = int_qubits(i)
        circ.append(("MS", q0, q1, 0.0, 0.0, 0.6))
    return circ
